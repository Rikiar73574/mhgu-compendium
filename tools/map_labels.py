"""Emit only the bounds of baked map labels from a locally owned game dump."""
import argparse
from pathlib import Path
from extract_map_pngs import decode

def bounds(image):
    pixels=image.load()
    white={(x,y) for y in range(image.height) for x in range(image.width)
           if min(pixels[x,y][:3])>=240 and pixels[x,y][3]>=240}
    boxes=[]
    while white:
        point=white.pop();pending=[point];component=[point]
        while pending:
            x,y=pending.pop()
            for adjacent in ((x-1,y),(x+1,y),(x,y-1),(x,y+1)):
                if adjacent in white:
                    white.remove(adjacent);pending.append(adjacent);component.append(adjacent)
        xs,ys=zip(*component);left,top,right,bottom=min(xs),min(ys),max(xs)+1,max(ys)+1
        if 4<=right-left<=40 and 8<=bottom-top<=28:
            # Map quad is centered at (0,0); include its dark text outline.
            boxes.append((left-130,top-130,right-126,bottom-126))
    return sorted(boxes)

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('game_dir',type=Path);p.add_argument('output',type=Path);a=p.parse_args()
    rows=['//! Baked-label coordinates only, generated by tools/map_labels.py from an owned dump.',
          'pub const BOUNDS:[&[[f32;4]];28]=[',' &[], // 0']
    for stage in range(1,28):
        image=decode(a.game_dir/f'romfs/nativeNX/eng/GUI/99_texture/map/HD_map_{stage:02}dn_BM_NOMIP.tex')
        assert image.size==(256,256)
        rectangles=bounds(image)
        assert len(rectangles)<=32
        rows.append(' &['+','.join('['+','.join(f'{v}.' for v in box)+']' for box in rectangles)+f'], // {stage}')
    a.output.write_text('\n'.join(rows+["];",'']))
