from paths import ROOT,DATA,GENERATED,database
import json,textwrap,sqlite3,collections
from pathlib import Path
root=Path(__file__).resolve().parents[1]
d=json.loads((DATA/'catalog.json').read_text())
records=sorted(d['items'].values(),key=lambda r:r['name'])+sorted(d['weapons'].values(),key=lambda r:(r['type'],r['name']))
ids={r['id']:i for i,r in enumerate(records)}
connection=database()
connection.row_factory=sqlite3.Row
item_metadata={r['name'].casefold():dict(r) for r in connection.execute('select name,description,rarity,carry_capacity,buy,sell from items where _id<65536')}
places=json.loads((DATA/'locations.json').read_text())
place_names={p['_id']:p['name'] for p in places['locations']}
gathered=collections.defaultdict(list)
for r in places['gathering']:gathered[r['name'].casefold()].append(r)

weapon_rows=collections.defaultdict(list)
for w in connection.execute('select w.*,i.name from weapons w join items i on i._id=w._id'):
 weapon_rows[(w['name'],w['wtype'],w['attack'])].append(dict(w))
components=collections.defaultdict(list)
for part in connection.execute('select c.*,i.name,i.type item_type from components c join items i on i._id=c.component_item_id'):
 components[part['created_item_id']].append(dict(part))
item_ids={r['name']:ids[r['id']] for r in d['items'].values()}
supplemented=0
parents={}
for w in d['weapons'].values():
 for b in w['branches']:parents.setdefault(b['to'],[]).append((w['id'],f"From {w['name']} Lv{b['from_level']}"))
def lit(s):return json.dumps(s,ensure_ascii=False)
lines=['// Generated by tools/embed.py. Kiranico facts; see README.md.','use super::Entry;','pub static ENTRIES: &[Entry] = &[']
for r in records:
 body=[];links=[];weapon=r['id'].startswith('weapon/')
 if weapon:
  body+=[r['type'],'WEAPON LEVELS']
  for lv in r['levels']:
   body.append(f"Lv{lv['level']} {lv['name']}   Attack {lv['attack']}")
   stats=[v for v in lv['stats_text'] if v.strip()]
   body.append(' / '.join(stats))
  links+=parents.get(r['id'],[])
  links += [(b['to'],f"Lv{b['from_level']} -> {d['weapons'][b['to']]['name']}") for b in r['branches']]
  for recipe in r.get('recipes',[]):
   body+=['',f"LEVEL {recipe['level']}   {recipe['price_z']}z"]
   for mode in ['create','upgrade']:
    if not recipe[mode]['ingredients']:continue
    body.append(mode.upper())
    for item in recipe[mode]['ingredients']:
     body.append(f"{item['name']}  {item['quantity']} {'points' if item['kind']=='material_points' else 'required'}")
     if item['id'] in ids:links.append((item['id'],item['name']))
    for item in recipe[mode]['byproducts']:body.append(f"Produces {item['name']} x{item['quantity']}")
  verified_levels={recipe['level'] for recipe in r.get('recipes',[])}
  for lv in r['levels']:
   if lv['level'] in verified_levels:continue
   candidates=weapon_rows[(f"{lv['name']} {lv['level']}",r['type'],lv['attack'])]
   if len(candidates)!=1:
    body += ['',f"Lv{lv['level']} recipe unavailable"]
    continue
   w=candidates[0];parts=components[w['_id']];supplemented+=1
   body += ['',f"LEVEL {lv['level']}",'Recipes: MHGenDatabase']
   for mode in ['Create','Create B','Improve']:
    group=[x for x in parts if x['type']==mode and x['item_type']!='Weapon']
    if not group:continue
    cost=w['upgrade_cost'] if mode=='Improve' else w['creation_cost']
    body.append(f"{'Upgrade' if mode=='Improve' else mode}  {cost or 0}z")
    for part in group:
     body.append(f"{part['name']}  {part['quantity']} {'points' if part['item_type']=='Materials' else 'required'}"+(' [Key]' if part['key'] else ''))
     if part['name'] in item_ids:
      # Existing link format is namespaced Kiranico identity, not database IDs.
      item=records[item_ids[part['name']]]
      links.append((item['id'],part['name']))

 else:
  meta=item_metadata.get(r['name'].casefold())
  if meta:
   body += [meta['description'] or '',f"Rarity {meta['rarity']}",f"Carry limit {meta['carry_capacity']}"]
   if meta['buy'] and meta['buy']>0:body.append(f"Buy {meta['buy']}z")
   if meta['sell'] and meta['sell']>0:body.append(f"Sell {meta['sell']}z")
  body+=['ITEM SOURCES']
  for source in gathered[r['name'].casefold()]:
   rank='GR' if source['rank']=='G' else source['rank']
   body += [f"{place_names[source['location_id']]} - {rank}",f"{source['area']} / {source['site']} / node {source['group_num']}",f"x{source['quantity']} / {source['percentage']}%"+(" / Rare" if source['rare'] else " / Fixed" if source['fixed'] else "")]
  if gathered[r['name'].casefold()]:body+=['Gathering source: MHGenDatabase','']

  if not r['details_loaded'] and not gathered[r['name'].casefold()]:body+=['Acquisition details not imported yet.']
  elif not r.get('sources') and not gathered[r['name'].casefold()]:body+=['No supported acquisition rows found on source page.']
  else:
   for row in r.get('sources',[]):body += [row['kind']+(' - '+row['rank'] if row['rank'] else ''),' / '.join(row['fields'])]
 body+=['','Source: Kiranico MHGU',r['source_url']]
 # Structured item/weapon views replace this legacy prose and link dump.
 # Do not embed a second copy of the complete catalog in limited plugin memory.
 wrapped=''
 links=[]
 unique=list(dict.fromkeys(links))
 lines.append('Entry{name:'+lit(r['name'])+',kind:'+str(int(weapon))+',body:'+lit(wrapped)+',links:&['+','.join('('+str(ids[i])+','+lit(label)+')' for i,label in unique)+']},')
lines.append('];');(GENERATED/'catalog.rs').write_text('\n'.join(lines)+'\n')
print('Embedded',len(records),'entries;',supplemented,'weapon levels supplemented from exact type/name/attack matches')
